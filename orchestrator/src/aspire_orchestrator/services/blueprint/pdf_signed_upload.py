"""Supabase Storage helper — pre-signed PUT URL for blueprint uploads.

Provides two async helpers called by the /upload-init and /upload-complete
endpoints to eliminate the base64-JSON-in-body anti-pattern that caused
WinError 10053 / 413 TCP aborts on large PDFs.

Mirrors thumbnail_storage.py / pdf_raw_storage.py patterns:
  Law #6: Path always prefixed with suite_id — no cross-tenant access.
  Law #9: PDF bytes NEVER logged. Only sizes, durations, and hash prefixes.
  Law #3: Returns None on failure rather than raising — caller decides 503.

Storage bucket:  blueprint-raw-pdfs
Path scheme:     {suite_id}/{upload_id}/raw.pdf
  - upload_id is a UUID v4 generated at init time (NOT project_id which
    is created later in upload-complete).
"""

from __future__ import annotations

import hashlib
import logging
import time

import httpx

from aspire_orchestrator.config.settings import settings
from aspire_orchestrator.services.supabase_client import SupabaseClientError

logger = logging.getLogger(__name__)

_BUCKET = "blueprint-raw-pdfs"
_SIGN_TIMEOUT = 10.0   # Supabase URL-mint call — should be fast
_STREAM_TIMEOUT = 60.0  # Streaming download for hash — PDFs can be 25 MB
_STREAM_CHUNK_SIZE = 8 * 1024  # 8 KB chunks — consistent with existing patterns


def _storage_base_url() -> str:
    """Return the Supabase Storage v1 base URL."""
    url = settings.supabase_url
    if not url:
        raise SupabaseClientError("storage", detail="Missing ASPIRE_SUPABASE_URL")
    return f"{url.rstrip('/')}/storage/v1"


def _service_headers() -> dict[str, str]:
    """Build service-role auth headers (Law #9: key never logged)."""
    key = settings.supabase_service_role_key
    if not key:
        raise SupabaseClientError("storage", detail="Missing ASPIRE_SUPABASE_SERVICE_ROLE_KEY")
    return {
        "apikey": key,
        "Authorization": f"Bearer {key}",
    }


async def mint_signed_upload_url(
    suite_id: str,
    upload_id: str,
    correlation_id: str,
    expires_in_seconds: int = 600,
) -> str | None:
    """Mint a pre-signed PUT URL so the browser can upload raw bytes directly.

    Calls Supabase Storage write-sign endpoint:
      POST /storage/v1/object/upload/sign/{bucket}/{path}

    This is the WRITE-sign endpoint (different from the read-sign endpoint at
    /storage/v1/object/sign/{bucket}/{path} which grants GET access only).

    Args:
        suite_id:           Tenant UUID — used as path prefix (Law #6).
        upload_id:          UUID v4 generated by /upload-init, NOT project_id.
        correlation_id:     Request correlation ID for log tracing.
        expires_in_seconds: Signed URL TTL (default 600s = 10 min).

    Returns:
        Absolute signed URL string on success.
        None on any failure (caller emits 503).

    Law #9: Never logs auth keys or response bodies containing tokens.
            Only logs upload_id[:8], status code, and duration_ms.
    """
    object_path = f"{suite_id}/{upload_id}/raw.pdf"
    base = _storage_base_url()
    sign_url = f"{base}/object/upload/sign/{_BUCKET}/{object_path}"

    start = time.monotonic()
    try:
        hdrs = _service_headers()
        hdrs["Content-Type"] = "application/json"

        async with httpx.AsyncClient(timeout=_SIGN_TIMEOUT) as client:
            resp = await client.post(
                sign_url,
                json={"expiresIn": expires_in_seconds},
                headers=hdrs,
            )

        duration_ms = round((time.monotonic() - start) * 1000, 1)

        if resp.status_code not in (200, 201):
            logger.warning(
                "pdf_signed_upload: sign failed upload_id=%s status=%d duration_ms=%.1f corr=%s",
                upload_id[:8],
                resp.status_code,
                duration_ms,
                correlation_id[:8],
            )
            return None

        body = resp.json()
        # Defensive key lookup — Supabase may return signedURL or signedUrl or url
        signed_url: str | None = (
            body.get("signedURL")
            or body.get("signedUrl")
            or body.get("url")
        )
        if not signed_url:
            logger.warning(
                "pdf_signed_upload: sign response missing URL key upload_id=%s corr=%s",
                upload_id[:8],
                correlation_id[:8],
            )
            return None

        # Supabase Storage's upload/sign endpoint returns a URL that is missing
        # the `/storage/v1` prefix — either as a relative path ("/object/...")
        # or as an absolute URL without the prefix
        # ("https://*.supabase.co/object/..."). Normalize both shapes so
        # browser PUTs land on the correct Storage gateway.
        origin = (settings.supabase_url or "").rstrip("/")
        if signed_url.startswith("/"):
            signed_url = (
                f"{origin}{signed_url}"
                if signed_url.startswith("/storage/v1")
                else f"{origin}/storage/v1{signed_url}"
            )
        elif origin and "/storage/v1/" not in signed_url and signed_url.startswith(origin):
            # Absolute URL missing /storage/v1 prefix — insert it after the origin
            signed_url = signed_url.replace(origin, f"{origin}/storage/v1", 1)

        logger.info(
            "pdf_signed_upload: minted signed URL upload_id=%s duration_ms=%.1f corr=%s",
            upload_id[:8],
            duration_ms,
            correlation_id[:8],
        )
        return signed_url

    except httpx.TimeoutException:
        logger.warning(
            "pdf_signed_upload: sign request timed out upload_id=%s corr=%s",
            upload_id[:8],
            correlation_id[:8],
        )
        return None
    except SupabaseClientError:
        raise  # Missing credentials — let caller emit 503
    except Exception as exc:
        logger.warning(
            "pdf_signed_upload: sign error upload_id=%s error=%s corr=%s",
            upload_id[:8],
            type(exc).__name__,
            correlation_id[:8],
        )
        return None


async def stream_pdf_for_hash(
    suite_id: str,
    upload_id: str,
    correlation_id: str,
) -> tuple[bytes, str] | None:
    """Stream the uploaded PDF from Storage, compute SHA-256 in chunks.

    Downloads the object at {suite_id}/{upload_id}/raw.pdf using streaming
    so the full bytes are never held in memory simultaneously during hashing.
    After hashing, the accumulated bytes are returned for pipeline dispatch.

    Args:
        suite_id:       Tenant UUID — path prefix (Law #6).
        upload_id:      UUID v4 that was used in /upload-init.
        correlation_id: Request correlation ID for log tracing.

    Returns:
        (all_bytes, hex_digest) on success.
        None if the object cannot be fetched (missing, auth error, timeout).
        Caller emits 422 UPLOAD_OBJECT_NOT_FOUND on None.

    Law #9: Never logs raw bytes — only logs object path, size_bytes,
            hash_prefix (first 8 hex chars), and duration_ms.
    """
    object_path = f"{suite_id}/{upload_id}/raw.pdf"
    base = _storage_base_url()
    get_url = f"{base}/object/{_BUCKET}/{object_path}"

    start = time.monotonic()
    chunks: list[bytes] = []
    hasher = hashlib.sha256()

    try:
        hdrs = _service_headers()

        async with httpx.AsyncClient(timeout=_STREAM_TIMEOUT) as client:
            async with client.stream("GET", get_url, headers=hdrs) as resp:
                if resp.status_code == 404:
                    logger.warning(
                        "pdf_signed_upload: object not found upload_id=%s corr=%s",
                        upload_id[:8],
                        correlation_id[:8],
                    )
                    return None

                if resp.status_code not in (200, 206):
                    logger.warning(
                        "pdf_signed_upload: stream GET failed upload_id=%s status=%d corr=%s",
                        upload_id[:8],
                        resp.status_code,
                        correlation_id[:8],
                    )
                    return None

                async for chunk in resp.aiter_bytes(chunk_size=_STREAM_CHUNK_SIZE):
                    hasher.update(chunk)
                    chunks.append(chunk)

        all_bytes = b"".join(chunks)
        hex_digest = hasher.hexdigest()
        duration_ms = round((time.monotonic() - start) * 1000, 1)

        # Law #9: never log bytes — log only size + hash prefix
        logger.info(
            "pdf_signed_upload: streamed upload_id=%s size_bytes=%d hash_prefix=%s duration_ms=%.1f corr=%s",
            upload_id[:8],
            len(all_bytes),
            hex_digest[:8],
            duration_ms,
            correlation_id[:8],
        )
        return all_bytes, hex_digest

    except httpx.TimeoutException:
        logger.warning(
            "pdf_signed_upload: stream timed out upload_id=%s corr=%s",
            upload_id[:8],
            correlation_id[:8],
        )
        return None
    except SupabaseClientError:
        raise  # Missing credentials
    except Exception as exc:
        logger.warning(
            "pdf_signed_upload: stream error upload_id=%s error=%s corr=%s",
            upload_id[:8],
            type(exc).__name__,
            correlation_id[:8],
        )
        return None
